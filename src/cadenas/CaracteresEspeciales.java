package src.cadenas;

public class CaracteresEspeciales {
    public static void main(String[] args) {
        // \n salto de linea
        String cadena1 = "Hola\nMundo";
        System.out.println("cadena1 = " + cadena1);
        
        // \t tabulador
        cadena1 = "\tHola\tMundo\t";
        System.out.println("cadena1 = " + cadena1);

    }
}
